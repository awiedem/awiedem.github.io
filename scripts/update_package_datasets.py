#!/usr/bin/env python3
"""Write _data/package_datasets.yml: the dataset names each gerda package can load.

The Data page offers a "copy load code" button only for names listed here, so a
file the packages cannot load never gets a snippet that fails. Reads the catalogs
on the default branches of hhilbig/gerda (R) and hhilbig/gerda-py (Python).

Rerun after a package release:  python3 scripts/update_package_datasets.py
"""
import json
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R_CATALOG = "https://raw.githubusercontent.com/hhilbig/gerda/HEAD/R/gerda_catalog.R"
PY_CATALOG = "https://raw.githubusercontent.com/hhilbig/gerda-py/HEAD/src/gerda/_catalog.json"


def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read().decode("utf-8")


def main():
    r_names = sorted(set(re.findall(r'\bds\(\s*"([a-z0-9_]+)"', fetch(R_CATALOG))))
    py_names = sorted(entry["name"] for entry in json.loads(fetch(PY_CATALOG)))
    if not r_names or not py_names:
        raise SystemExit("empty catalog; not overwriting _data/package_datasets.yml")
    lines = ["# Generated by scripts/update_package_datasets.py; do not edit by hand.", "", "r:"]
    lines += [f"  - {name}" for name in r_names]
    lines += ["python:"]
    lines += [f"  - {name}" for name in py_names]
    (ROOT / "_data" / "package_datasets.yml").write_text("\n".join(lines) + "\n")
    print(f"R: {len(r_names)} datasets, Python: {len(py_names)} datasets")


if __name__ == "__main__":
    main()
